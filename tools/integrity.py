#!/usr/bin/env python3
"""Integrity and identity for this repository, in one place.

Two different failures, deliberately kept apart:

  drift     a file changed after review, or a file appeared that nobody reviewed
  imitation a checkout that is not this repository, or not this repository's history

`build` writes harness/integrity.lock: a digest per reviewed file plus one digest over the
whole set. `verify` recomputes and fails on anything added, removed or modified.

The honest limitation: a lock living in the repository it protects can be regenerated by
whoever controls that repository. It detects drift against a reviewed state and it makes a
trojan drop visible in a diff, which is what review can act on. It is not a signature.
SECURITY.md pins the set digest separately, so rewriting the lock means touching a second
file that reviewers read.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "harness" / "integrity.lock"
CANONICAL_REMOTE = "github.com/1243353366/assay"

# Anything CI executes or the harness imports belongs here.
COVERED = (
    "harness",
    "tools",
    "tests",
    "pyproject.toml",
    "conftest.py",
    ".github/workflows",
    "requirements.txt",
    "requirements-dev.txt",
)
SKIP_SUFFIXES = (".pyc", ".lock")
SKIP_PARTS = ("__pycache__", ".pytest_cache")


def _files() -> list[Path]:
    out: list[Path] = []
    for entry in COVERED:
        target = ROOT / entry
        if target.is_file():
            out.append(target)
        elif target.is_dir():
            out.extend(sorted(p for p in target.rglob("*") if p.is_file()))
    return [p for p in out
            if not p.name.endswith(SKIP_SUFFIXES)
            and not any(part in SKIP_PARTS for part in p.parts)]


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build() -> dict:
    files = {str(p.relative_to(ROOT)): _digest(p) for p in _files()}
    body = json.dumps(files, indent=2, sort_keys=True)
    return {
        "algorithm": "sha256",
        "covers": list(COVERED),
        "file_count": len(files),
        "files": files,
        "set_digest": hashlib.sha256(body.encode()).hexdigest(),
    }


def verify() -> tuple[bool, list[str], dict]:
    if not LOCK.is_file():
        return False, ["no lock file: run 'build' and commit the result"], {}
    expected = json.loads(LOCK.read_text())
    actual = build()
    problems: list[str] = []
    for name, digest in sorted(expected["files"].items()):
        if name not in actual["files"]:
            problems.append(f"removed: {name}")
        elif actual["files"][name] != digest:
            problems.append(f"modified: {name}")
    for name in sorted(set(actual["files"]) - set(expected["files"])):
        problems.append(f"added and never reviewed: {name}")
    if expected["set_digest"] != actual["set_digest"]:
        problems.append("set digest differs")
    return not problems, problems, actual


def identity() -> tuple[bool, list[str]]:
    """Is this checkout the canonical repository, at a commit?"""
    problems: list[str] = []
    try:
        def git(*args: str) -> str:
            return subprocess.run(["git", *args], cwd=ROOT, capture_output=True,
                                  text=True, timeout=10).stdout.strip()

        remote = re.sub(r"//[^@]*@", "//", git("config", "--get", "remote.origin.url"))
        branch = git("rev-parse", "--abbrev-ref", "HEAD")
        commit = git("rev-parse", "--short", "HEAD")
    except (OSError, subprocess.SubprocessError) as exc:
        return False, [f"cannot read git state: {type(exc).__name__}"]
    if CANONICAL_REMOTE not in remote:
        problems.append(f"origin is not the canonical repository: {remote or '(none)'}")
    if not commit:
        problems.append("no commit at HEAD")
    print(f"origin {remote or '(none)'}  branch {branch or '?'}  commit {commit or '?'}",
          file=sys.stderr)
    return not problems, problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="integrity and identity for this repository")
    parser.add_argument("action", choices=["build", "verify", "digest", "identity", "all"])
    args = parser.parse_args(argv)

    if args.action == "digest":
        print(build()["set_digest"])
        return 0
    if args.action == "build":
        data = build()
        LOCK.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
        print(f"wrote {LOCK.relative_to(ROOT)}: {data['file_count']} files")
        print(f"set digest {data['set_digest']}")
        return 0

    ok_drift, drift_problems, actual = verify()
    ok_ident, ident_problems = (True, [])
    if args.action in ("identity", "all"):
        ok_ident, ident_problems = identity()

    for problem in drift_problems + ident_problems:
        print(f"  {problem}", file=sys.stderr)
    if ok_drift and ok_ident:
        print(f"integrity ok: {actual['file_count']} files match the reviewed set "
              f"({actual['set_digest'][:16]})")
        return 0
    print("integrity FAILED", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
